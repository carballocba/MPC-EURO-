#!/usr/bin/env python3
"""Generate the renderer's tiny glyph table from our licensed DejaVu font.
The community bitmap's original font provenance was not identified in its
vendored subset; we supply our own glyph data instead of relying on it.
"""
from pathlib import Path
from PIL import Image,ImageDraw,ImageFont
root=Path(__file__).resolve().parents[1]
chars=' ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789.-/_>%+:#'
font=ImageFont.truetype(str(root/'vendor/fonts/DejaVuSansMono.ttf'),64)
rows=[]
for c in chars:
    im=Image.new('L',(72,72));dr=ImageDraw.Draw(im)
    dr.text((36,36),c,font=font,anchor='mm',fill=255)
    im=im.resize((9,9),Image.Resampling.LANCZOS)
    rows.append('    {'+','.join(str(v) for v in im.tobytes())+'},')
header='/* GENERATED by tools/gen_font.py from DejaVuSansMono.ttf.\n * Glyph data: Bitstream Vera font license; see vendor/fonts/LICENSE.\n * No community bitmap glyph data is retained. */\n'
header+='static const uint8_t font8x8[][81] = {\n'+'\n'.join(rows)+'\n};\n'
header+='static const char font_chars[] = "'+chars+'";\n'
(root/'vendor/mpc/tools/vendor/force-shadow/src/font8x8.h').write_text(header)
